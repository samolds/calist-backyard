"""Write plan/backyard_plan.svg from geometry.py (standard library only)."""
from pathlib import Path

import geometry as g

OUT = Path(__file__).resolve().parent.parent / "plan" / "backyard_plan.svg"
NSS = 'vector-effect="non-scaling-stroke"'


def fmt(v):
    return f"{v:g}"


def path_d(cmds):
    return " ".join(cmd + " " + ", ".join(f"{fmt(x)} {fmt(y)}" for x, y in pts) for cmd, *pts in cmds)


def rect(r):
    x, y, w, h = r
    return f'<rect x="{fmt(x)}" y="{fmt(y)}" width="{fmt(w)}" height="{fmt(h)}" {NSS}/>'


def circle(c):
    cx, cy, r = c
    return f'<circle cx="{fmt(cx)}" cy="{fmt(cy)}" r="{fmt(r)}" {NSS}/>'


def group(key, items, width=2):
    fill, op, stroke = g.COLORS[key]
    fill_attr = f'fill="{fill}" fill-opacity="{op}"' if fill else 'fill="none"'
    body = "\n".join("    " + i for i in items)
    return (f'  <g id="{key}" {fill_attr} stroke="{stroke}" stroke-width="{width}" '
            f'stroke-linejoin="round" stroke-linecap="round" {NSS}>\n{body}\n  </g>')


def main():
    vb_w, vb_h = g.PAD_W + 8, g.VIEW_BOTTOM + 4
    base = [f'<polyline points="{" ".join(f"{fmt(x)},{fmt(y)}" for x, y in pts)}" {NSS}/>'
            for pts in g.BASE_LINES]
    base += [f'<path d="{path_d(p)}" {NSS}/>' for p in (g.GRASS_PATH, g.CONCRETE_PATH)]
    base += [rect(r) for r in g.BASE_RECTS] + [circle(c) for c in g.BASE_CIRCLES]

    sail_pts = " ".join(f"{fmt(x)},{fmt(y)}" for x, y in g.SAIL)
    cords = [f'<line x1="{fmt(a[0])}" y1="{fmt(a[1])}" x2="{fmt(b[0])}" y2="{fmt(b[1])}" {NSS}/>'
             for a, b in zip(g.SAIL, g.SAIL_MOUNTS)]
    _, _, pstroke = g.COLORS["pergola"]
    pergola = [f'<g fill-opacity="0.08">{rect(g.PERGOLA)}</g>']
    pergola += [f'<g fill="none" stroke-dasharray="3 2" stroke-width="1">{circle(c)}</g>' for c in g.PERGOLA_PIERS]
    pergola += [f'<g fill-opacity="0.15" stroke-width="0.6">{rect(r)}</g>' for r in g.PERGOLA_SLATS]
    pergola += [f'<g fill-opacity="0.45" stroke-width="1.2">{rect(r)}</g>' for r in g.PERGOLA_BEAMS]
    pergola += [f'<g fill="{pstroke}" fill-opacity="0.9">{rect(r)}</g>' for r in g.PERGOLA_POSTS]
    pergola += [f'<line x1="{fmt(a[0])}" y1="{fmt(a[1])}" x2="{fmt(b[0])}" y2="{fmt(b[1])}" '
                f'stroke="#0b4d23" stroke-width="3" {NSS}/>' for a, b in g.PERGOLA_BRACES]

    parts = [
        '<?xml version="1.0" encoding="UTF-8"?>',
        "<!-- Generated by src/render_svg.py from src/geometry.py. Do not edit by hand. 1 unit = 1 inch. -->",
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="-4 -4 {fmt(vb_w)} {fmt(vb_h)}" '
        f'width="{fmt(vb_w * 2.5)}" height="{fmt(vb_h * 2.5)}">',
        f'  <rect x="-4" y="-4" width="{fmt(vb_w)}" height="{fmt(vb_h)}" fill="#fff"/>',
        group("base", base, 1.5),
        group("tree_canopy", [f'<g stroke-dasharray="6 4">{circle(g.TREE_CANOPY)}</g>'], 1.5),
        group("planters", [rect(r) for r in g.PLANTERS]),
        group("tree", [circle(g.TREE)]),
        group("pergola", pergola, 1.5),
        group("shrubs", [circle(c) for c in g.SHRUBS]),
        group("composter", [rect(g.COMPOSTER)]),
        group("sail", [f'<polygon points="{sail_pts}" {NSS}/>']),
        group("cords", cords),
        "</svg>",
    ]
    OUT.write_text("\n".join(parts) + "\n")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
